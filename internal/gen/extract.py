#!/usr/bin/env python3
"""
extract.py - generates Go enum tables from the YARA-X Rust reference.

This is a BUILD-TIME tool only. It is not part of the shipped Go library,
which depends on nothing outside the standard library.

Reads:
  <ref>/parser/src/cst/syntax_kind.rs
  <ref>/parser/src/tokenizer/tokens.rs

Writes:
  kinds_gen.go   -- SyntaxKind constants, names, SyntaxKind->TokenID map
  tokens_gen.go  -- TokenID constants, names, descriptions

Transcribing these tables by hand is error-prone and the mapping is
load-bearing (e.g. SyntaxKind DIV maps to TokenID BACKSLASH, because YARA
spells integer division '\\'). Extracting mechanically removes that risk.
"""

import re
import sys
import os

def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()

def enum_variants(src, enum_name):
    """Pull the identifier list out of a Rust enum body."""
    m = re.search(r"enum\s+" + enum_name + r"\b[^{]*\{", src)
    if not m:
        sys.exit("enum %s not found" % enum_name)
    i = m.end()
    depth = 1
    body_start = i
    while depth:
        c = src[i]
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
        i += 1
    body = src[body_start:i - 1]
    # Strip comments and attributes so they can't contribute identifiers.
    body = re.sub(r"//[^\n]*", "", body)
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"#\[[^\]]*\]", "", body, flags=re.S)
    out = []
    for line in body.split("\n"):
        line = line.strip().rstrip(",").strip()
        if re.fullmatch(r"[A-Z][A-Z0-9_]*", line):
            out.append(line)
    return out

def pair_map(src, fn_name, lhs_enum, rhs_enum):
    """Extract `LHS::A => RHS::B,` arms from inside a named fn."""
    m = re.search(r"fn\s+" + fn_name + r"\s*\(", src)
    if not m:
        sys.exit("fn %s not found" % fn_name)
    seg = src[m.end():]
    pairs = []
    seen = set()
    pat = re.compile(lhs_enum + r"::([A-Z0-9_]+)\s*=>\s*" + rhs_enum + r"::([A-Z0-9_]+)")
    for a, b in pat.findall(seg):
        if a in seen:      # first arm wins, matching Rust match semantics
            continue
        seen.add(a)
        pairs.append((a, b))
    return pairs

def descriptions(src):
    """TokenId::X => "desc"," arms from TokenId::description()."""
    m = re.search(r"fn\s+description\s*\(", src)
    seg = src[m.end():]
    out = {}
    for name, desc in re.findall(r'TokenId::([A-Z0-9_]+)\s*=>\s*"((?:[^"\\]|\\.)*)"', seg):
        out.setdefault(name, desc)
    return out

def go_header(pkg):
    return (
        "// Code generated by internal/gen/extract.py from the YARA-X Rust\n"
        "// reference implementation. DO NOT EDIT.\n\n"
        "package %s\n\n" % pkg
    )

def main():
    ref = sys.argv[1]
    out = sys.argv[2]
    sk_src = read(os.path.join(ref, "parser/src/cst/syntax_kind.rs"))
    tk_src = read(os.path.join(ref, "parser/src/tokenizer/tokens.rs"))

    kinds = enum_variants(sk_src, "SyntaxKind")
    tokens = enum_variants(tk_src, "TokenId")
    k2t = pair_map(sk_src, "token_id", "SyntaxKind", "TokenId")
    descs = descriptions(tk_src)

    # ---- kinds_gen.go ----
    b = [go_header("yarrow")]
    b.append("// SyntaxKind identifies a node or token in the concrete syntax tree.\n")
    b.append("type SyntaxKind uint8\n\nconst (\n")
    for i, k in enumerate(kinds):
        b.append("\t%s SyntaxKind = %d\n" % (k, i))
    b.append(")\n\n")
    b.append("var syntaxKindNames = [...]string{\n")
    for k in kinds:
        b.append("\t%s: \"%s\",\n" % (k, k))
    b.append("}\n\n")
    b.append("// String returns the kind's name as used in CST dumps.\n")
    b.append("func (k SyntaxKind) String() string {\n")
    b.append("\tif int(k) < len(syntaxKindNames) {\n\t\treturn syntaxKindNames[k]\n\t}\n")
    b.append("\treturn \"UNKNOWN\"\n}\n\n")

    # kindTokenID: 255 sentinel means "no associated token".
    b.append("// noToken marks a SyntaxKind with no corresponding TokenID.\n")
    b.append("const noToken TokenID = 0xff\n\n")
    b.append("var kindTokenID = func() [%d]TokenID {\n" % len(kinds))
    b.append("\tvar m [%d]TokenID\n" % len(kinds))
    b.append("\tfor i := range m {\n\t\tm[i] = noToken\n\t}\n")
    for a, bb in k2t:
        b.append("\tm[%s] = T_%s\n" % (a, bb))
    b.append("\treturn m\n}()\n\n")
    b.append("// TokenID returns the token that this SyntaxKind matches against,\n")
    b.append("// or noToken if the kind is a non-terminal.\n")
    b.append("func (k SyntaxKind) TokenID() TokenID { return kindTokenID[k] }\n")
    with open(os.path.join(out, "kinds_gen.go"), "w") as f:
        f.write("".join(b))

    # ---- tokens_gen.go ----
    b = [go_header("yarrow")]
    b.append("// TokenID identifies a lexical token produced by the tokenizer.\n")
    b.append("type TokenID uint8\n\nconst (\n")
    for i, t in enumerate(tokens):
        b.append("\tT_%s TokenID = %d\n" % (t, i))
    b.append(")\n\n")
    b.append("var tokenNames = [...]string{\n")
    for t in tokens:
        b.append("\tT_%s: \"%s\",\n" % (t, t))
    b.append("}\n\n")
    b.append("func (t TokenID) String() string {\n")
    b.append("\tif int(t) < len(tokenNames) {\n\t\treturn tokenNames[t]\n\t}\n\treturn \"UNKNOWN\"\n}\n\n")
    b.append("var tokenDescriptions = [...]string{\n")
    for t in tokens:
        if t in descs:
            d = descs[t].replace("\\\\", "\\\\")
            b.append("\tT_%s: \"%s\",\n" % (t, d))
    b.append("}\n\n")
    b.append("// Description is the human-readable form used in error messages.\n")
    b.append("func (t TokenID) Description() string {\n")
    b.append("\tif int(t) < len(tokenDescriptions) && tokenDescriptions[t] != \"\" {\n")
    b.append("\t\treturn tokenDescriptions[t]\n\t}\n\treturn t.String()\n}\n")

    # Natural SyntaxKind for each TokenID, used when a token is consumed
    # during error recovery rather than matched against a TokenSet.
    b.append("// tokenKind is the SyntaxKind a token carries when emitted directly.\n")
    b.append("var tokenKind = [...]SyntaxKind{\n")
    kindset = set(kinds)
    for t in tokens:
        if t in kindset:
            b.append("\tT_%s: %s,\n" % (t, t))
    b.append("}\n\n")
    b.append("// Kind returns the SyntaxKind naturally associated with the token.\n")
    b.append("func (t TokenID) Kind() SyntaxKind {\n")
    b.append("\tif int(t) < len(tokenKind) {\n\t\treturn tokenKind[t]\n\t}\n\treturn UNKNOWN\n}\n")
    with open(os.path.join(out, "tokens_gen.go"), "w") as f:
        f.write("".join(b))

    print("kinds=%d tokens=%d mapped=%d descs=%d" % (len(kinds), len(tokens), len(k2t), len(descs)))

main()
